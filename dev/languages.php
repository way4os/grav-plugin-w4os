<?php
// Writes the language files of the plugin, languages/<lang>.yaml (Grav's format), from the catalog of opensim-engine (vendor: the
// texts every bridge of a grid shares) and i18n/<lang>.yaml (the texts of Grav alone).
// A text missing in a language is the English one.
//
//   php dev/languages.php [folder]     default: languages/ of the plugin (composer languages)

require dirname(__DIR__).'/vendor/autoload.php';

use OpenSim\I18n\Catalog;
use Symfony\Component\Yaml\Yaml;

/** The languages of Grav, and the locale of the catalog of each. */
const LANGUAGES = ['en' => 'en', 'fr' => 'fr_FR', 'de' => 'de_DE', 'it' => 'it_IT', 'nl' => 'nl_NL', 'pt-BR' => 'pt_BR', 'cy' => 'cy_GB'];

$root = dirname(__DIR__);
$folder = rtrim($argv[1] ?? "$root/languages", '/');
is_dir($folder) || mkdir($folder, 0755, true);
$own = fn (string $lang) => is_file("$root/i18n/$lang.yaml") ? (array) (Yaml::parseFile("$root/i18n/$lang.yaml")['w4os'] ?? []) : [];

foreach (LANGUAGES as $lang => $locale) {
    $texts = array_merge(Catalog::messages('en'), $locale === 'en' ? [] : Catalog::messages($locale));
    $texts += array_merge($own('en'), $own($lang));
    $out = "# Generated by dev/languages.php from the catalog of opensim-engine (".Catalog::locale($locale).") and i18n/$lang.yaml: do\n# not edit, change those and run composer languages.\nw4os:\n";
    foreach ($texts as $key => $text) {
        $out .= "  $key: '".str_replace("'", "''", $text)."'\n";
    }
    file_put_contents("$folder/$lang.yaml", $out);
}
